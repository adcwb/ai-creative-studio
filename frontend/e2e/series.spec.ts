import {selectOption, expectControlValue} from './support/controls'
import {test,expect,type APIRequestContext,type Page} from '@playwright/test'
import {randomUUID} from 'node:crypto'
import type {SeriesEntry} from '../src/features/series/types'
const api='http://127.0.0.1:8081/api/v1',query='?space_id=personal-demo'
async function create(request:APIRequestContext,path:string,data:unknown){const r=await request.post(api+path+query,{headers:{'Idempotency-Key':randomUUID()},data});expect(r.status()).toBe(201);return await r.json() as SeriesEntry}
async function fixture(request:APIRequestContext){const series=await create(request,'/series',{title:`合成系列-${randomUUID()}`,summary:'两位伙伴在四季中逐渐理解彼此。',profile:{duration_seconds:120,output_resolution:'2160p',aspect_ratio:'9:16'}});const season=await create(request,`/series/${series.id}/seasons`,{});return{series,season}}
