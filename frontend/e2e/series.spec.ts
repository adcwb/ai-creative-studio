test('an acknowledged episode with a lost response resumes after refresh without creating or overwriting a project',async({page,request})=>{
 const {series,season}=await fixture(request)
 await page.goto(`/series/${series.id}`)
 await page.getByRole('button',{name:'添加一集',exact:true}).click()
 await page.getByLabel('名称',{exact:true}).fill('原始创作种子')
 let acknowledged:SeriesEntry|undefined
 await page.route(`**/api/v1/seasons/${season.id}/episodes?*`,async route=>{
  if(route.request().method()!=='POST')return route.continue()
  const response=await route.fetch();acknowledged=await response.json() as SeriesEntry
  await route.abort('failed')
 })
 await page.getByRole('button',{name:'保存',exact:true}).click()
 await expect(page.getByText('上次保存结果尚未确认。请用原请求核对，避免重复创建。',{exact:true})).toBeVisible()
 expect(acknowledged?.project_id).toBeTruthy()
 const updated=await request.put(`${api}/projects/${acknowledged!.project_id}${query}`,{headers:{'Idempotency-Key':randomUUID()},data:{expected_version:1,title:'用户后来编辑的标题',brief:'重试目录创建不得覆盖这份当前故事简述。'}})
 expect(updated.status()).toBe(200)
 await page.unroute(`**/api/v1/seasons/${season.id}/episodes?*`)
 page.on('dialog',d=>void d.accept())
 await page.reload()
 await page.getByRole('button',{name:'添加一集',exact:true}).click()
 await expectControlValue(page.getByLabel('名称',{exact:true}), '原始创作种子')
 await expect(page.getByLabel('名称',{exact:true})).toBeDisabled()
 await page.route(`**/api/v1/seasons/${season.id}/episodes?*`,route=>route.request().method()==='POST'?route.fulfill({status:403,contentType:'application/json',body:JSON.stringify({error:{code:'role_denied',message:'当前权限不能修改此系列'}})}):route.continue())
 await page.getByRole('button',{name:'核对并重试保存',exact:true}).click()
 await expect(page.getByText('当前权限不能修改此系列',{exact:true})).toBeVisible()
 await expect(page.getByLabel('名称',{exact:true})).toBeDisabled()
 await page.unroute(`**/api/v1/seasons/${season.id}/episodes?*`)
 await page.getByRole('button',{name:'核对并重试保存',exact:true}).click()
 await expect(page).toHaveURL(new RegExp(`/projects/${acknowledged!.project_id}/brief$`))
 await expect(page.getByRole('heading',{name:'用户后来编辑的标题',exact:true})).toBeVisible()
 const list=await (await request.get(`${api}/seasons/${season.id}/episodes${query}`)).json()
 expect(list.items).toHaveLength(1);expect(list.items[0].title).toBe('用户后来编辑的标题')
})
test('201 episode metadata entries remain reachable through directory pagination',async({page,request})=>{
 test.setTimeout(120000)
 const {series,season}=await fixture(request)
 let finalEpisode:SeriesEntry|undefined
 for(let i=1;i<=201;i++)finalEpisode=await create(request,`/seasons/${season.id}/episodes`,{title:`合成剧集 ${i}`})
 await page.goto(`/series/${series.id}`)
 await expect(page.locator('.series-episode-card')).toHaveCount(20)
 for(let n=40;n<=200;n+=20){await page.getByRole('button',{name:'加载更多剧集',exact:true}).click();await expect(page.locator('.series-episode-card')).toHaveCount(n)}
 await page.getByRole('button',{name:'加载更多剧集',exact:true}).click()
 await expect(page.locator('.series-episode-card')).toHaveCount(201)
 await expect(page.getByRole('button',{name:'加载更多剧集',exact:true})).toHaveCount(0)
 const last=page.locator('.series-episode-card').last();await expect(last).toContainText('第 201 集')
 await last.getByRole('button',{name:'调整集号',exact:true}).click()
 await page.getByLabel('新的编号',{exact:true}).fill('7')
 await selectOption(page.getByRole('combobox',{name:'调整方式',exact:true}), 'insert')
 await page.getByRole('button',{name:'保存编号',exact:true}).click()
 await expect(page.locator('.series-episode-card')).toHaveCount(20)
 const inserted=page.locator('.series-episode-card').filter({has:page.getByRole('link',{name:'合成剧集 201',exact:true})})
 await expect(inserted).toContainText('第 7 集')
 const shifted=page.locator('.series-episode-card').filter({has:page.getByRole('link',{name:'合成剧集 7',exact:true})})
 await expect(shifted).toContainText('第 8 集')
 await inserted.getByRole('link',{name:'进入这一集',exact:true}).click()
 await expect(page).toHaveURL(new RegExp(`/projects/${finalEpisode!.project_id}/brief$`))
 await expect(page.locator('.series-context')).toContainText('第 7 集')
 await noOverflow(page)
})
