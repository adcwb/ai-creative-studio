import { test, expect } from '@playwright/test'

test('create mock image, save, reload, switch space, and show failure', async ({page}, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByText('模拟演示模式')).toBeVisible()
  await expect(page.getByRole('button', {name:'创建模拟图像'})).toBeDisabled()
  const prompt = `春日咖啡海报 ${testInfo.project.name} ${Date.now()}`
  await page.getByLabel('描述你的画面').fill(prompt)
  await page.getByRole('button', {name:'创建模拟图像'}).click()
  const card = page.locator('.task').filter({hasText:prompt})
  await expect(card.getByText('模拟完成', {exact:true})).toBeVisible()
  await expect(card.locator('img')).toBeVisible()
  expect(await card.locator('img').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
  await page.getByRole('button', {name:'创建模拟图像'}).click()
  await expect(page.locator('.task').filter({hasText:prompt})).toHaveCount(1)
  await card.getByRole('button', {name:'保存到素材库'}).click()
  await expect(card.getByRole('button', {name:'已保存'})).toBeDisabled()
  await page.getByRole('button', {name:/素材库/}).first().click()
  await expect(page.locator('.asset-grid').getByText(prompt)).toBeVisible()
  await page.reload()
  await page.getByRole('button', {name:/素材库/}).first().click()
  await expect(page.locator('.asset-grid').getByText(prompt)).toBeVisible()
  await page.getByLabel('选择演示空间').selectOption('team-demo')
  await page.getByRole('button', {name:/素材库/}).first().click()
  await expect(page.getByText(prompt, {exact:true})).toHaveCount(0)
  await page.getByRole('button', {name:'图像创作', exact:true}).click()
  await page.getByLabel('描述你的画面').fill(`[mock-fail] 故障测试 ${testInfo.project.name}`)
  await page.getByRole('button', {name:'创建模拟图像'}).click()
  await expect(page.locator('.task').filter({hasText:testInfo.project.name}).getByText('执行失败', {exact:true})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({path: testInfo.outputPath('studio.png'), fullPage:true})
  expect(errors).toEqual([])
})

test('connection failure is visible and recoverable', async ({page}) => {
  await page.route('**/api/v1/tasks?*', route => route.abort())
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('无法同步服务')
  await page.unroute('**/api/v1/tasks?*')
  await page.getByRole('button', {name:'重新连接'}).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
