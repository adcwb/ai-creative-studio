  await expect(page.getByRole('option', {name: '保存新的加密凭据', exact: true})).toHaveJSProperty('disabled', true)
  await page.getByRole('button', {name: '保存模型声明', exact: true}).click()
  await expect(page.getByText('管理配置已保存；执行时使用最新权限与版本校验，未进行真实调用。', {exact: true})).toBeVisible()
