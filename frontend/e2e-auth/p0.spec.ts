import {test,expect} from '@playwright/test'
import {navigateTo,openNavigation} from '../e2e/support/navigation'
test('personal and team spaces, access boundaries and explicit backend settings',async({page},info)=>{
 await page.goto('/')
 await page.getByRole('button',{name:'创建新账户'}).click()
 await page.locator('#auth-email').fill(`p0-${info.project.name}@example.invalid`)
 await page.locator('#auth-password').fill('Synthetic-P0-passphrase!')
 await page.getByRole('button',{name:'注册并登录'}).click()
 await expect(page.getByLabel('描述你的画面')).toBeVisible()
 await navigateTo(page,'/settings/organization')
 await expect(page.getByText('个人空间仅你自己可访问。需要共同创作时，请创建团队空间。')).toBeVisible()
 await expect(page.getByRole('button',{name:'保存成员权限'})).toHaveCount(0)
 await navigateTo(page,'/settings/spaces')
 await page.getByLabel('团队名称',{exact:true}).fill('品牌故事团队')
 await page.getByRole('button',{name:'创建团队空间',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('团队空间已创建')
 await page.locator('.space-card').filter({hasText:'品牌故事团队'}).getByRole('button',{name:'进入空间'}).click()
 await expect(page.locator('.space-card').filter({hasText:'品牌故事团队'})).toContainText('当前空间')
 await navigateTo(page,'/settings/organization')
 await expect(page.getByRole('button',{name:'保存成员权限'})).toBeVisible()
 await expect(page.locator('.member-list')).toContainText('所有者')
 await navigateTo(page,'/settings/backend')
 await expect(page.getByRole('heading',{name:'后端配置',exact:true})).toHaveCount(2)
 await expect(page.getByLabel('FRONTEND_ORIGIN',{exact:true})).toHaveValue('http://localhost:5175')
 await page.getByText('数据库与存储',{exact:true}).click()
 const secret=page.getByLabel('DATABASE_URL',{exact:true})
 await expect(secret).toHaveValue('')
 await secret.fill('postgres://synthetic:p0-secret@example.invalid/test')
 await page.getByRole('button',{name:'保存后端配置'}).click()
 await expect(page.getByRole('status')).toContainText('请重启')
 await expect(secret).toHaveValue('')
 expect(await page.content()).not.toContain('p0-secret')
 await page.reload()
 await expect(page.getByLabel('DATABASE_URL',{exact:true})).toHaveValue('')
 if(info.project.name==='desktop')await page.setViewportSize({width:1920,height:1080})
 await page.screenshot({path:`test-results/p0-real-backend-${info.project.name}.png`,fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await openNavigation(page)
 await expect(page.getByRole('link',{name:'后端配置',exact:true})).toHaveAttribute('aria-current','page')
 if(info.project.name==='mobile'){
  await page.keyboard.press('Escape')
  await expect(page.locator('.menu-toggle')).toBeFocused()
 }
})
