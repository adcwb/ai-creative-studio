test('unconfirmed save survives reload and replays its original identity without a duplicate', async ({page}) => {
  const {query} = await setup(page, false)
  await page.getByLabel('描述你的画面', {exact: true}).fill('等待核对的清晨花园，安静的光线')
  await page.getByRole('button', {name: '保存当前描述', exact: true}).click()
  const editor = page.getByRole('dialog', {name: '保存自己的提示词', exact: true})
  await editor.getByLabel('提示词名称', {exact: true}).fill('保存结果待确认')
  let originalKey = ''
  await page.route('**/api/v1/prompt-templates?**', async route => {
    if (route.request().method() !== 'POST') {await route.continue(); return}
    originalKey = route.request().headers()['idempotency-key']
    const response = await route.fetch()
    expect(response.status()).toBe(201)
    await route.fulfill({status: 503, contentType: 'application/json', body: JSON.stringify({error: {code: 'prompt_storage_error', message: '合成保存响应丢失，请核对原请求'}})})
  })
  await editor.getByRole('button', {name: '保存提示词', exact: true}).click()
  await expect(editor.getByRole('button', {name: '重试原保存请求', exact: true})).toBeVisible()
  await expect(editor.getByLabel('提示词名称', {exact: true})).toBeDisabled()
  await page.unroute('**/api/v1/prompt-templates?**')
  page.once('dialog', dialog => dialog.accept())
  await page.reload()
  await page.getByRole('button', {name: '恢复并核对保存', exact: true}).click()
  const retry = page.waitForResponse(r => r.url().includes('/prompt-templates?') && r.request().method() === 'POST')
  await page.getByRole('button', {name: '重试原保存请求', exact: true}).click()
  expect((await retry).request().headers()['idempotency-key']).toBe(originalKey)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const result = await (await page.request.get(api + '/prompt-templates' + query)).json()
  expect(result.items).toHaveLength(1)
  expect(result.items[0].version.number).toBe(1)
})

