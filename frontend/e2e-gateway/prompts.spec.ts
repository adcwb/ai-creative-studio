  const editor = page.getByRole('dialog', {name: '编辑我的提示词', exact: true})
  const draft = '这是我的未保存草稿，保留细节'
  await editor.getByLabel('提示词正文', {exact: true}).fill(draft)
  expect((await page.request.post(api + '/prompt-templates/' + first.template.id + '/versions' + query, {headers: {...headers, 'Idempotency-Key': crypto.randomUUID()}, data: {expected_head_version_id: first.version.id, version: {...first.version, id: undefined, template_id: undefined, space_id: undefined, number: undefined, sha256: undefined, created_by: undefined, created_at: undefined, body: '另一位编辑的新版本'}}})).status()).toBe(201)
