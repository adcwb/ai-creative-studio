import {test,expect} from '@playwright/test'
import {navigateTo} from '../e2e/support/navigation'
test('encrypted gateway key create, preserve, update and explicit check use only a fake upstream',async({page,request},info)=>{
 await page.goto('/')
 await page.getByRole('button',{name:'创建新账户',exact:true}).click()
 await page.locator('#auth-email').fill(`gateway-${info.project.name}-${Date.now()}@example.invalid`)
 await page.locator('#auth-password').fill('Synthetic-key-test-password!')
 await page.getByRole('button',{name:'注册并登录',exact:true}).click()
 await expect(page.locator('.app-shell')).toBeVisible()
 await navigateTo(page,'/settings/preferences')
 await page.getByRole('button',{name:'管理当前组织的模型网关',exact:true}).click()
 await page.getByRole('tab',{name:'AI 网关',exact:true}).click()
 await page.getByRole('button',{name:'添加 AI 网关',exact:true}).click()
 const form=page.locator('.model-editor-form')
 await expect(form.getByLabel('新的 API Key',{exact:true})).toBeVisible()
 await form.getByLabel('网关名称',{exact:true}).fill('Synthetic local gateway')
 await form.getByLabel('服务地址',{exact:true}).fill('http://127.0.0.1:5193/v1')
 await form.getByLabel('新的 API Key',{exact:true}).fill('synthetic-key-A')
 const before=(await (await request.get('http://127.0.0.1:5193/__state')).json()).calls
 await form.getByRole('button',{name:'保存网关',exact:true}).click()
 await expect(form).toHaveCount(0)
 await expect(page.getByRole('cell',{name:'已加密',exact:true})).toBeVisible()
 expect((await (await request.get('http://127.0.0.1:5193/__state')).json()).calls).toBe(before)
 const session=await (await page.request.get('http://localhost:8084/api/v1/auth/session')).json()
 const query='?space_id='+session.spaces[0].id
 const report=await (await page.request.get('http://localhost:8084/api/v1/model-management'+query)).json()
 expect(JSON.stringify(report)).not.toContain('synthetic-key-A')
 expect(await page.evaluate(()=>JSON.stringify(localStorage))).not.toContain('synthetic-key-A')
 await page.getByRole('button',{name:'编辑',exact:true}).click()
 await expect(form.getByRole('combobox',{name:'凭据操作',exact:true})).toHaveValue('keep')
 await expect(form.locator('input[type=password]')).toHaveCount(0)
 await form.getByLabel('网关名称',{exact:true}).fill('Renamed synthetic gateway')
 await form.getByRole('button',{name:'保存网关',exact:true}).click()
 await expect(form).toHaveCount(0)
 await page.getByRole('button',{name:'检查连接',exact:true}).click()
 await expect(page.getByText('连接成功，发现 1 个模型；生成能力尚未验证。',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'编辑',exact:true}).click()
 await form.getByRole('combobox',{name:'凭据操作',exact:true}).selectOption('set')
 await expect(form.getByLabel('新的 API Key',{exact:true})).toHaveValue('')
 await form.getByLabel('新的 API Key',{exact:true}).fill('synthetic-key-B')
 await form.getByRole('button',{name:'保存网关',exact:true}).click()
 await expect(form).toHaveCount(0)
 await page.reload()
 await page.getByRole('button',{name:'管理当前组织的模型网关',exact:true}).click()
 await page.getByRole('tab',{name:'AI 网关',exact:true}).click()
 await page.getByRole('button',{name:'检查连接',exact:true}).click()
 await expect(page.getByText('连接成功，发现 1 个模型；生成能力尚未验证。',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'编辑',exact:true}).click()
 await form.getByRole('combobox',{name:'凭据操作',exact:true}).selectOption('set')
 await form.getByLabel('新的 API Key',{exact:true}).fill('synthetic-rejected-key')
 await form.getByRole('button',{name:'保存网关',exact:true}).click()
 await expect(form).toHaveCount(0)
 await page.getByRole('button',{name:'检查连接',exact:true}).click()
 await expect(page.getByText(/模型目录检查失败/)).toBeVisible()
 await expect(page.locator('body')).not.toContainText('synthetic-rejected-key')
 await page.getByRole('button',{name:'编辑',exact:true}).click()
 await form.getByRole('combobox',{name:'凭据操作',exact:true}).selectOption('revoke')
 await form.getByRole('button',{name:'保存网关',exact:true}).click()
 await expect(form).toHaveCount(0)
 await expect(page.getByRole('cell',{name:'已撤销',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'检查连接',exact:true})).toBeDisabled()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
