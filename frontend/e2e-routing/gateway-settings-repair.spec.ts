import {test, expect} from '@playwright/test'
const fixture = 'http://127.0.0.1:5189'
test.beforeEach(async ({request}) => {await request.post(fixture + '/__test__/reset')})

test('compact navigation keeps every icon on one axis', async ({page}, info) => {
  test.skip(info.project.name !== 'desktop')
  await page.goto('/settings/models')
  await page.getByRole('button', {name: '收起侧栏', exact: true}).click()
  const geometry = await page.locator('.sidebar').evaluate(sidebar => {
    const icons = [...sidebar.querySelectorAll<HTMLElement>('.app-nav a .icon, .group-toggle .icon')]
    const centers = icons.map(icon => {const rect = icon.getBoundingClientRect(); return rect.x + rect.width / 2})
    return {centers, overflow: sidebar.scrollWidth > sidebar.clientWidth}
  })
  expect(Math.max(...geometry.centers) - Math.min(...geometry.centers)).toBeLessThan(2)
  expect(geometry.overflow).toBe(false)
  await page.screenshot({path: 'test-results/repaired-compact-sidebar.png', fullPage: true})
})

test('gateway metadata remains saveable without encryption and notice text flows normally', async ({page, request}) => {
  const management = await (await request.get(fixture + '/api/v1/model-management')).json()
  await request.post(fixture + '/__test__/reset', {data: {management: {...management, secret_storage_available: false}}})
  await page.goto('/settings/models')
  await page.getByRole('tab', {name: 'AI 网关', exact: true}).click()
  const notice = page.locator('#model-panel-gateways > .notice')
  await expect(notice).toBeVisible()
  expect(await notice.evaluate(el => getComputedStyle(el).display)).toBe('block')
  await page.getByRole('button', {name: '添加 AI 网关', exact: true}).click()
  const form = page.locator('.model-editor-form')
  await form.getByLabel('网关名称', {exact: true}).fill('连接草稿')
  await form.getByLabel('服务地址', {exact: true}).fill('https://synthetic.example/v1')
  await expect(form.getByLabel('凭据操作', {exact: true})).toHaveValue('keep')
  await expect(form.getByRole('button', {name: '保存网关'})).toBeEnabled()
  await form.getByRole('button', {name: '保存网关'}).click()
  await expect(form).toHaveCount(0)
  await expect(page.locator('.gateway-table').getByText('连接草稿', {exact: true})).toBeVisible()
})

test('gateway accepts a key, scheduled sync and a deduplicated catalog import', async ({page, request}) => {
  await page.goto('/settings/models')
  await page.getByRole('tab', {name: 'AI 网关', exact: true}).click()
  await page.getByRole('button', {name: '添加 AI 网关', exact: true}).click()
  const form = page.locator('.model-editor-form')
  await form.getByLabel('网关名称', {exact: true}).fill('目录网关')
  await form.getByLabel('服务地址', {exact: true}).fill('https://synthetic.example/v1')
  await form.getByLabel('新的 API Key', {exact: true}).fill('synthetic-test-key')
  await form.getByLabel('自动同步模型', {exact: true}).selectOption('15')
  await form.getByRole('button', {name: '保存网关'}).click()
  await expect(form).toHaveCount(0)
  await page.locator('.gateway-table').getByRole('button', {name: '同步模型', exact: true}).click()
  await expect(page.getByRole('status')).toContainText('新增 1 个待配置模型')
  await page.locator('.gateway-table').getByRole('button', {name: '同步模型', exact: true}).click()
  await expect(page.getByRole('status')).toContainText('新增 0 个待配置模型')
  const state = await (await request.get(fixture + '/__test__/state')).json()
  expect(state.management.gateways[0].sync_interval_minutes).toBe(15)
  expect(state.management.models).toHaveLength(1)
  expect(state.management.models[0]).toMatchObject({enabled: false, pending: true, capabilities: []})
  await page.getByRole('tab', {name: '网关模型', exact: true}).click()
  await expect(page.getByText('待配置', {exact: true})).toBeVisible()
  await page.screenshot({path: `test-results/repaired-gateway-${test.info().project.name}.png`, fullPage: true})
})

test('deployment settings redact secrets, save a patch and survive reload', async ({page, request}) => {
  await request.post(fixture + '/__test__/reset', {data: {deploymentAdmin: true}})
  await page.goto('/settings/backend')
  const panel = page.locator('.system-config-panel')
  await expect(panel.getByRole('heading', {name: '后端配置'})).toBeVisible()
  await expect(panel.getByLabel('DATA_DIR', {exact: true})).toBeDisabled()
  await panel.getByLabel('FRONTEND_ORIGIN', {exact: true}).fill('https://new.example')
  await panel.getByText('数据库与存储', {exact: true}).click()
  await expect(panel.getByLabel('DATABASE_URL', {exact: true})).toHaveValue('')
  await panel.getByLabel('DATABASE_URL', {exact: true}).fill('postgres://synthetic:test@localhost/db')
  await panel.getByRole('button', {name: '保存后端配置'}).click()
  await expect(panel.getByRole('status')).toContainText('请重启')
  await expect(panel.getByLabel('DATABASE_URL', {exact: true})).toHaveValue('')
  await page.reload()
  await expect(panel.getByLabel('FRONTEND_ORIGIN', {exact: true})).toHaveValue('https://new.example')
  await page.screenshot({path: `test-results/repaired-system-settings-${test.info().project.name}.png`, fullPage: true})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

