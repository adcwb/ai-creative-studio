test('an uncertain image submission retains its idempotency key across project navigation', async ({page, request}) => {
  await page.goto('/studio')
  await page.getByLabel('描述你的画面').fill('结果未知的测试图像')
  const keys: string[] = []
  page.on('request', request => {if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/v1/tasks') keys.push(request.headers()['idempotency-key'])})
  await page.route('**/api/v1/tasks?*', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    await route.fetch(); await route.abort()
  }, {times: 1})
  await page.getByRole('button', {name: '创建模拟图像', exact: true}).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await navigate(page, '/projects')
  await navigate(page, '/studio')
  await expect(page.getByLabel('描述你的画面')).toHaveValue('结果未知的测试图像')
  await page.getByRole('button', {name: '创建模拟图像', exact: true}).click()
  await expect.poll(() => keys.length).toBe(2)
  expect(keys[0]).toBe(keys[1])
  const state = await (await request.get(fixture + '/__test__/state')).json()
  expect(state.tasks.filter((task: {prompt: string}) => task.prompt === '结果未知的测试图像')).toHaveLength(1)
})

