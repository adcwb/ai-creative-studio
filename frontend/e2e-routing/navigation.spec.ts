test('desktop and mobile layouts expose navigation and preserve language selection', async ({page}, info) => {
  await page.goto('/studio')
  await expect(page.getByLabel('描述你的画面')).toBeVisible()
  if (info.project.name === 'mobile') {
    await page.getByRole('button', {name: '打开导航'}).click()
    await expect(page.getByRole('dialog', {name: '主导航'})).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', {name: '打开导航'})).toBeFocused()
    await page.getByRole('button', {name: '打开导航'}).click()
  }
  await page.getByLabel('界面语言').selectOption('en')
  if (info.project.name === 'mobile') await page.getByRole('button', {name: 'Close navigation', exact: true}).last().click()
  await expect(page.getByRole('heading', {name: 'Image creation', exact: true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', {name: 'Image creation', exact: true})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path: info.outputPath('studio.png'), fullPage: true})
  if (info.project.name === 'desktop') {
    for (const width of [1440, 1920]) {
      await page.setViewportSize({width, height: 1000})
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({path: info.outputPath(`studio-${width}.png`), fullPage: true})
    }
    await page.goto('/projects')
    await expect(page.locator('.project-card')).toBeVisible()
    await page.screenshot({path: info.outputPath('projects.png'), fullPage: true})
    await page.goto('/settings/models')
    await expect(page.getByLabel('Model identifier', {exact: true})).toBeVisible()
    await page.screenshot({path: info.outputPath('models.png'), fullPage: true})
  }
})
