import { expect, test } from '@playwright/test'

const fixture = 'http://127.0.0.1:5189'
test.beforeEach(async ({request, page}) => {
  await request.post(`${fixture}/__test__/reset`, {data: {}})
  page.on('pageerror', error => {throw error})
})

test('library keeps historical cards when a new version is saved and archived', async ({page}, testInfo) => {
  await page.goto('/library')
  await page.getByRole('button', {name: '建立资产卡', exact: true}).click()
  await page.getByLabel('资产名称', {exact: true}).fill('钟楼修理师')
  await page.getByLabel('发型', {exact: true}).fill('黑色短发')
  await page.getByLabel('禁止变化项（每行一项，最多 20 项）').fill('左侧袖口的铜扣')
  await page.getByRole('button', {name: '创建资产卡', exact: true}).click()
  await expect(page.getByRole('heading', {name: '钟楼修理师 · 版本 1'})).toBeVisible()
  await page.screenshot({path: testInfo.outputPath('library.png'), fullPage: true})
  await page.getByLabel('服装', {exact: true}).fill('深绿色外套')
  await page.getByRole('button', {name: '保存为新版本', exact: true}).click()
  await expect(page.getByRole('heading', {name: '钟楼修理师 · 版本 2'})).toBeVisible()
  await page.locator('.library-version-list button').filter({hasText: '版本 1'}).click()
  await expect(page.getByRole('region', {name: '历史版本预览'})).not.toContainText('深绿色外套')
  await page.getByRole('button', {name: '归档资产', exact: true}).click()
  await page.getByRole('button', {name: '确认归档', exact: true}).click()
  await expect(page.getByText('已归档，历史版本仍可查看。')).toBeVisible()
  await expect(page.getByLabel('资产名称', {exact: true})).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('uncertain library save survives refresh and replays the original request', async ({page, request}) => {
  await request.post(`${fixture}/__test__/reset`, {data: {libraryDropReply: true}})
  await page.goto('/library')
  await page.getByRole('button', {name: '建立资产卡', exact: true}).click()
  await page.getByLabel('资产名称', {exact: true}).fill('同一角色')
  await page.getByRole('button', {name: '创建资产卡', exact: true}).click()
  await expect(page.getByRole('button', {name: '使用原请求核对结果'})).toBeVisible()
  await expect(page.getByLabel('资产名称', {exact: true})).toBeDisabled()
  page.on('dialog', dialog => void dialog.accept())
  await page.reload()
  await expect(page.getByText('发现未确认的资产保存请求，请先核对结果。')).toBeVisible()
  await page.getByRole('button', {name: '使用原请求核对结果'}).click()
  await expect(page.getByRole('heading', {name: '同一角色 · 版本 1'})).toBeVisible()
  const response = await request.get(`${fixture}/api/v1/library/assets?space_id=personal-demo`)
  expect((await response.json()).items).toHaveLength(1)
})

test('read-only library is usable in English and does not offer writes', async ({page, request}) => {
  await request.post(`${fixture}/__test__/reset`, {data: {role: 'viewer'}})
  await page.addInitScript(() => localStorage.setItem('studio.locale', 'en'))
  await page.goto('/library')
  await expect(page.getByRole('heading', {name: 'Creative library', exact: true})).toBeVisible()
  await expect(page.getByRole('button', {name: 'Create asset card', exact: true})).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('project binding survives refresh without duplicating or following a new library head', async ({page, request}) => {
  await request.post(`${fixture}/__test__/reset`, {data: {libraryBindingDropReply: true}})
  const card = {name: '钟楼修理师', description: '', prohibited_changes: ['铜扣'], character: {appearance: '', hair: '短发', costume: '', expression: '', voice_notes: ''}}
  const created = await request.post(`${fixture}/api/v1/library/assets?space_id=personal-demo`, {headers: {'Idempotency-Key': 'test-binding-asset'}, data: {kind: 'character', card, references: []}})
  const original = await created.json()
  await page.goto('/projects/story-1/references')
  await page.getByRole('combobox', {name: '创作资产', exact: true}).selectOption(original.asset.id)
  await page.getByRole('combobox', {name: '参考版本', exact: true}).selectOption(original.version.id)
  await page.getByRole('button', {name: '绑定此版本', exact: true}).click()
  await expect(page.getByRole('button', {name: '使用原请求核对结果', exact: true})).toBeEnabled()
  page.on('dialog', dialog => void dialog.accept())
  await page.reload()
  await page.getByRole('button', {name: '使用原请求核对结果', exact: true}).click()
  await expect(page.getByRole('button', {name: '绑定此版本', exact: true})).toBeVisible()
  await request.post(`${fixture}/api/v1/library/assets/${original.asset.id}/versions?space_id=personal-demo`, {headers: {'Idempotency-Key': 'test-binding-next'}, data: {kind: 'character', expected_asset_version_id: original.version.id, card: {...card, name: '新版角色'}, references: []}})
  const view = await (await request.get(`${fixture}/api/v1/projects/story-1/library-bindings?space_id=personal-demo`)).json()
  expect(view.items).toHaveLength(1)
  expect(view.items[0].asset_version_id).toBe(original.version.id)
  await expect(page.locator('.drama-history')).toContainText('钟楼修理师')
})
