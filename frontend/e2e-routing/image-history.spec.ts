import {test, expect} from '@playwright/test'
import {chooseSpace, closeNavigation, navigateTo} from '../e2e/support/navigation'

const fixture = 'http://127.0.0.1:5189'
test('paginated image history preserves navigation and resets at the workspace boundary', async ({page, request}, info) => {
  await request.post(fixture + '/__test__/reset', {data: {}})
  const [base] = await (await request.get(fixture + '/api/v1/tasks?space_id=personal-demo')).json()
  const tasks = Array.from({length: 8}, (_, index) => ({...base, id: `history-${index}`, prompt: `分页记录 ${index}`, created_at: new Date(Date.UTC(2026, 10, 13, 0, index)).toISOString()}))
  const team = {...base, id: 'team-history', space_id: 'team-demo', prompt: '团队独立记录'}
  await request.post(fixture + '/__test__/reset', {data: {tasks: [...tasks, team]}})
  const lastPage = await (await request.get(fixture + '/api/v1/tasks?space_id=personal-demo&page=999&page_size=6')).json()
  expect(lastPage).toMatchObject({total: 8, page: 2, page_size: 6, running: 0})
  expect(lastPage.items.map((task: {id: string}) => task.id)).toEqual(['history-1', 'history-0'])
  expect(await (await request.get(fixture + '/api/v1/tasks?space_id=personal-demo')).json()).toHaveLength(8)
  expect((await request.get(fixture + '/api/v1/tasks?space_id=personal-demo&page=0')).status()).toBe(400)
  expect(await (await request.get(fixture + '/api/v1/tasks?space_id=empty-space&page=3')).json()).toMatchObject({items: [], total: 0, page: 1, running: 0})
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize(info.project.name === 'desktop' ? {width: 1920, height: 1080} : {width: 390, height: 844})
  await page.goto('/studio')
  const pagination = page.getByRole('navigation', {name: '创作记录分页'})
  await expect(page.locator('.task')).toHaveCount(6)
  await expect(page.locator('.task').first()).toContainText('分页记录 7')
  await expect(pagination).toContainText('共 8 条')
  await expect(pagination.getByRole('button', {name: '上一页'})).toBeDisabled()
  await pagination.getByRole('button', {name: '下一页'}).click()
  await expect(page.locator('.task')).toHaveCount(2)
  await expect(pagination).toContainText('第 2 / 2 页')
  await expect(pagination.getByRole('button', {name: '下一页'})).toBeDisabled()
  await navigateTo(page, '/assets')
  await expect(page).toHaveURL(/\/assets$/)
  await expect(page.getByRole('heading', {name: '素材库', exact: true})).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(/\/studio$/)
  await expect(pagination).toContainText('第 2 / 2 页')
  await chooseSpace(page, 'team-demo')
  await closeNavigation(page)
  await expect(page.locator('.task')).toHaveCount(1)
  await expect(page.locator('.task')).toContainText('团队独立记录')
  await expect(pagination).toContainText('第 1 / 1 页')
  await chooseSpace(page, 'personal-demo')
  await closeNavigation(page)
  await expect(page.locator('.task')).toHaveCount(6)
  await expect(pagination).toContainText('第 1 / 2 页')
  await expect(page.locator('.task').first().locator('.origin-label')).toHaveText('模拟图像 · 非 AI 生成')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
  await page.screenshot({path: info.outputPath('image-history.png'), fullPage: true})
})
