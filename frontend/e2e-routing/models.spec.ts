import { expect, test } from '@playwright/test'

const fixture = 'http://127.0.0.1:5189'
test.beforeEach(async ({request}) => {await request.post(`${fixture}/__test__/reset`);})

for (const editor of ['model', 'gateway'] as const) {
  test(`${editor} dialog preserves catalog position, drafts and save behavior`, async ({page, request}) => {
    const management = await (await request.get(`${fixture}/api/v1/model-management`)).json()
    const gateways = Array.from({length: 30}, (_, index) => ({id: `gateway-${index}`, name: `测试网关 ${index}`, base_url: 'https://synthetic.example/v1', enabled: true, timeout_seconds: 120, version: 1, secret_status: 'encrypted'}))
    const models = Array.from({length: 60}, (_, index) => ({id: `model-${index}`, gateway_id: gateways[0].id, name: `测试模型 ${index}`, model: `vendor/model-${index}`, capabilities: [], enabled: false, pending: true, version: 1, max_output_tokens: 3000, json_output: true, video_seconds: 4, video_size: '1280x720', currency: 'USD', maximum_minor: 0, price_source: ''}))
    await request.post(`${fixture}/__test__/reset`, {data: {management: {...management, gateways, models}}})
    await page.goto('/settings/models')
    await page.getByRole('tab', {name: editor === 'model' ? '网关模型' : 'AI 网关', exact: true}).click()
    const panel = page.locator(editor === 'model' ? '#model-panel-models' : '#model-panel-gateways')
    const form = panel.locator('.model-editor-form')
    const dialog = page.getByRole('dialog', {name: editor === 'model' ? '编辑网关模型' : '编辑 AI 网关', exact: true})
    const name = form.getByLabel(editor === 'model' ? '模型显示名称' : '网关名称', {exact: true})
    for (const index of [20, 20, 1]) {
      const edit = panel.locator('tbody tr').nth(index).getByRole('button', {name: '编辑', exact: true})
      await edit.scrollIntoViewIfNeeded()
      const scrollY = await page.evaluate(() => window.scrollY)
      await edit.click()
      await expect(dialog).toBeVisible()
      await expect(name).toBeInViewport()
      await expect(name).toBeFocused()
      await expect(name).toHaveValue(editor === 'model' ? models[index].name : gateways[index].name)
      await expect(form.getByRole('button', {name: '取消', exact: true})).toBeInViewport()
      await expect(dialog.getByRole('heading')).toBeInViewport()
      await form.getByRole('button', {name: '取消', exact: true}).focus()
      await page.keyboard.press('Tab')
      await expect(dialog.getByRole('button', {name: '关闭编辑'})).toBeFocused()
      await page.keyboard.press('Shift+Tab')
      await expect(form.getByRole('button', {name: '取消', exact: true})).toBeFocused()
      expect(await page.evaluate(() => window.scrollY)).toBe(scrollY)
      if (index !== 1) {
        await page.keyboard.press('Escape')
        await expect(dialog).toHaveCount(0)
        await expect(edit).toBeFocused()
        expect(await page.evaluate(() => window.scrollY)).toBe(scrollY)
      }
    }
    await name.fill('已修改的名称')
    await page.keyboard.press('Escape')
    const confirmation = page.getByRole('dialog', {name: '放弃未保存的修改？', exact: true})
    await expect(confirmation).toBeVisible()
    await confirmation.getByRole('button', {name: '继续编辑', exact: true}).click()
    await expect(name).toHaveValue('已修改的名称')
    if (editor === 'model') {
      await form.getByLabel('文本推理', {exact: true}).check()
      await form.getByLabel('启用此模型', {exact: true}).check()
    }
    const saveButton = form.getByRole('button', {name: editor === 'model' ? '保存模型' : '保存网关', exact: true})
    await expect(saveButton).toBeInViewport()
    const saveURL = editor === 'model' ? '**/gateway-models/model-1?*' : '**/ai-gateways/gateway-1?*'
    await page.route(saveURL, route => route.fulfill({status: 409, json: {error: {code: 'model_config_conflict', message: '测试保存失败，请重试'}}}))
    await saveButton.click()
    await expect(dialog.getByRole('alert')).toContainText('测试保存失败，请重试')
    await expect(dialog.getByRole('alert')).toBeInViewport()
    await expect(dialog.getByRole('heading')).toBeInViewport()
    await expect(name).toHaveValue('已修改的名称')
    await page.unroute(saveURL)
    await page.screenshot({path: `test-results/${editor}-dialog-${test.info().project.name}.png`})
    await saveButton.click()
    await expect(form).toHaveCount(0)
    const state = await (await request.get(`${fixture}/__test__/state`)).json()
    const saved = editor === 'model' ? state.management.models.find((item: {id: string}) => item.id === 'model-1') : state.management.gateways.find((item: {id: string}) => item.id === 'gateway-1')
    expect(saved.name).toBe('已修改的名称')
    if (editor === 'model') expect(saved).toMatchObject({enabled: true, pending: false, capabilities: ['text']})
    await panel.getByRole('button', {name: editor === 'model' ? '添加模型' : '添加 AI 网关', exact: true}).click()
    await expect(name).toBeInViewport()
    await name.fill('放弃的新草稿')
    await form.getByRole('button', {name: '取消', exact: true}).click()
    await confirmation.getByRole('button', {name: '放弃修改', exact: true}).click()
    await expect(form).toHaveCount(0)
  })
}

test('configure two gateways, multiple models, and independent feature routes', async ({page, request}) => {
  await page.goto('/settings/models')
  await expect(page.getByRole('heading', {name: '模型管理', exact: true})).toBeVisible()
  await page.getByRole('tab', {name: 'AI 网关', exact: true}).click()
  for (const name of ['文本主网关', '分镜网关']) {
    await page.getByRole('button', {name: '添加 AI 网关', exact: true}).click()
    const form = page.locator('.model-editor-form')
    await form.getByLabel('网关名称', {exact: true}).fill(name)
    await form.getByLabel('服务地址', {exact: true}).fill(`https://${name === '文本主网关' ? 'first' : 'second'}.example.com/v1`)
    await form.getByRole('combobox', {name: '凭据操作', exact: true}).selectOption('set')
    await form.getByLabel('新的 API Key', {exact: true}).fill('synthetic-browser-test-key')
    await form.getByRole('button', {name: '保存网关', exact: true}).click()
    await expect(form).toHaveCount(0)
  }
  await page.getByRole('tab', {name: '网关模型', exact: true}).click()
  for (const [gateway, name, model] of [['gateway-1', '通用文本', 'vendor/shared'], ['gateway-1', '快速文本', 'vendor/fast'], ['gateway-2', '分镜推理', 'vendor/shared']]) {
    await page.getByRole('button', {name: '添加模型', exact: true}).click()
    const form = page.locator('.model-editor-form')
    await form.getByRole('combobox', {name: '所属网关', exact: true}).selectOption(gateway)
    await form.getByLabel('模型显示名称', {exact: true}).fill(name)
    await form.getByLabel('上游模型 ID', {exact: true}).fill(model)
    await form.getByRole('button', {name: '保存模型', exact: true}).click()
    await expect(form).toHaveCount(0)
  }
  await page.getByRole('tab', {name: 'AI 网关', exact: true}).click()
  await page.locator('tr').filter({has: page.getByText('文本主网关', {exact: true})}).getByRole('button', {name: '编辑', exact: true}).click()
  await page.locator('.model-editor-form').getByLabel('网关名称', {exact: true}).fill('未保存的网关草稿')
  await page.locator('.model-editor-form').getByRole('button', {name: '取消', exact: true}).click()
  await page.getByRole('dialog', {name: '放弃未保存的修改？'}).getByRole('button', {name: '继续编辑'}).click()
  await expect(page.locator('.model-editor-form').getByLabel('网关名称', {exact: true})).toHaveValue('未保存的网关草稿')
  await page.getByRole('button', {name: '关闭编辑', exact: true}).click()
  await page.getByRole('dialog', {name: '放弃未保存的修改？'}).getByRole('button', {name: '放弃修改'}).click()
  await page.getByRole('tab', {name: '功能绑定', exact: true}).click()
  const script = page.locator('.feature-binding-table tbody tr').filter({hasText: '剧本生成'})
  await script.getByRole('combobox', {name: '剧本生成 AI 网关', exact: true}).selectOption('gateway-1')
  await expect(script.getByRole('combobox', {name: '剧本生成 模型', exact: true}).locator('option')).toHaveCount(3)
  await script.getByRole('combobox', {name: '剧本生成 模型', exact: true}).selectOption('model-1')
  await script.getByRole('button', {name: '保存绑定'}).click()
  await expect(script.getByRole('button', {name: '保存绑定'})).toBeDisabled()
  const storyboard = page.locator('.feature-binding-table tbody tr').filter({hasText: '分镜规划'})
  await storyboard.getByRole('combobox', {name: '分镜规划 AI 网关', exact: true}).selectOption('gateway-1')
  await storyboard.getByRole('combobox', {name: '分镜规划 模型', exact: true}).selectOption('model-1')
  await storyboard.getByRole('combobox', {name: '分镜规划 AI 网关', exact: true}).selectOption('gateway-2')
  await expect(storyboard.getByRole('combobox', {name: '分镜规划 模型', exact: true})).toHaveValue('')
  await expect(storyboard.getByRole('combobox', {name: '分镜规划 模型', exact: true}).locator('option')).toHaveCount(2)
  await storyboard.getByRole('combobox', {name: '分镜规划 模型', exact: true}).selectOption('model-3')
  await storyboard.getByRole('button', {name: '保存绑定'}).click()
  await expect(storyboard.getByRole('button', {name: '保存绑定'})).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('combobox', {name: '剧本生成 AI 网关', exact: true})).toHaveValue('gateway-1')
  await expect(page.getByRole('combobox', {name: '分镜规划 AI 网关', exact: true})).toHaveValue('gateway-2')
  const state = await (await request.get(`${fixture}/__test__/state`)).json()
  expect(state.management.models).toHaveLength(3)
  expect(state.management.bindings.map((item: {model_config_id: string}) => item.model_config_id)).toEqual(['model-1', 'model-3'])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path: `test-results/model-routing-${test.info().project.name}.png`, fullPage: true})
  const loaded = page.waitForResponse(response => response.url().includes('/projects/story-1?') && response.request().method() === 'GET')
  await page.goto('/projects/story-1/storyboard')
  expect((await loaded).status()).toBe(200)
  await expect(page.locator('.runtime-model-picker select').nth(0)).toHaveValue('gateway-2')
  await expect(page.locator('.runtime-model-picker select').nth(1)).toHaveValue('model-3')
})

